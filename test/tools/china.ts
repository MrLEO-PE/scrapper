import { getSchools } from "../../src/store/db.ts";
import { buildRecipients } from "../../src/export/recipients.ts";
import { isTargetCountry, targetCountries } from "../../src/directoryconfig.ts";
const all = [...getSchools().values()].filter((s) => (s.country ?? "") === "China");
const any = (s: any) => s.career_email || s.contact_email || s.school_email;
const withAny = all.filter(any);
console.log("China schools in the database:", all.length);
console.log("  with a careers/HR email:", all.filter((s) => s.career_email).length);
console.log("  with at least one email (any kind):", withAny.length);
console.log("  with NO email at all:", all.length - withAny.length, "| of those with a website:", all.filter((s) => !any(s) && s.website).length, "| no website:", all.filter((s) => !any(s) && !s.website).length);
console.log("  China in the target countries config:", isTargetCountry("China", targetCountries()));
const rec = buildRecipients(all.filter((s) => isTargetCountry(s.country, targetCountries())).concat([]));
const cn = rec.filter((r) => r.country === "China");
console.log("\nEmail tab rows for China (one per ADDRESS, groups merged):", cn.length);
console.log("  by tier:", ["careers", "named", "general"].map((t) => `${t} ${cn.filter((r) => r.tier === t).length}`).join(" | "));
console.log("  by letter quality:", ["unique", "group", "none"].map((t) => `${t} ${cn.filter((r) => r.factQuality === t).length}`).join(" | "));
console.log("  shared inboxes (cover >1 school):", cn.filter((r) => r.schools.length > 1).length, "covering", cn.filter((r) => r.schools.length > 1).reduce((a, r) => a + r.schools.length, 0), "schools");
console.log("  applied to a school in the last 60 days:", cn.filter((r) => r.appliedRecently).length);
console.log("  letter ready AND specific fact (what the default filter shows):", cn.filter((r) => r.factQuality !== "none" && r.body).length);
